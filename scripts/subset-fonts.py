from pathlib import Path
import json

from fontTools import subset
from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont


root = Path(__file__).resolve().parent.parent
inputs = [root / "index.html", *sorted((root / "src").rglob("*.ts")),
          *sorted((root / "src").rglob("*.tsx")), *sorted((root / "src").rglob("*.css")),
          root / "public/media/manifest.json"]
characters = set(range(32, 127))
for source in inputs:
    characters.update(map(ord, source.read_text(encoding="utf-8")))

faces = [(400, "55-Regular"), (500, "65-Medium"), (600, "75-SemiBold"), (700, "85-Bold")]
css = ["/* Generated by scripts/subset-fonts.py; full fonts in fonts.css cover new characters. */"]
report = []
for weight, suffix in faces:
    original = root / "public/fonts/alibaba-puhuiti" / f"AlibabaPuHuiTi-3-{suffix}.woff2"
    output = original.with_stem(original.stem + "-subset")
    with TTFont(original) as font:
        covered = sorted(characters & font.getBestCmap().keys())
        options = subset.Options()
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.glyph_names = True
        options.recalc_timestamp = False
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=covered)
        subsetter.subset(font)
        font.save(output)

    # 核对当前字符的字宽与轮廓，保留已冻结的字形和断行。
    with TTFont(original) as full, TTFont(output) as small:
        before, after = full.getBestCmap(), small.getBestCmap()
        assert set(covered) <= after.keys()
        full_glyphs, small_glyphs = full.getGlyphSet(), small.getGlyphSet()
        for codepoint in covered:
            first, second = before[codepoint], after[codepoint]
            assert full["hmtx"][first] == small["hmtx"][second], hex(codepoint)
            a, b = RecordingPen(), RecordingPen()
            full_glyphs[first].draw(a)
            small_glyphs[second].draw(b)
            assert a.value == b.value, hex(codepoint)

    ranges = ",".join(f"U+{value:X}" for value in covered)
    css.append(f"""@font-face {{
  font-family: 'Alibaba PuHuiTi 3.0';
  font-style: normal;
  font-display: swap;
  font-weight: {weight};
  src: url('./fonts/alibaba-puhuiti/{output.name}') format('woff2');
  unicode-range: {ranges};
}}""")
    report.append({"weight": weight, "characters": len(covered), "originalBytes": original.stat().st_size,
                   "subsetBytes": output.stat().st_size, "coverageAndGlyphs": "PASS"})

(root / "public/font-subsets.css").write_text("\n\n".join(css) + "\n", encoding="utf-8")
print(json.dumps(report, indent=2))
